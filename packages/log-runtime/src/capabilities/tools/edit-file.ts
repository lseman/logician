/**
 * pi_edit's own hashline spec (`editDescription("hashline")` in
 * @logician/log-natives, ported from oh-my-pi's prompts/hashline.md).
 * Embedded statically rather than loaded at tool-definition time so a
 * missing/unbuilt native addon can't take the whole tool schema down with
 * it — only actually running a hashline edit needs the addon loaded.
 */
const HASHLINE_INPUT_DESCRIPTION = `Line-anchored patch language: name original lines/gaps to replace, insert, cut, or paste; then give new content. \`:\` headers take \`+\` body rows; colonless paste \`PUT\`, \`CUT\`, \`REM\`, \`MV\` take none.

Section header: \`[path#TAG]\` — TAG is the 4-hex snapshot from the latest read/search of that file, required on every section. This tool only edits one file per call: the header must name the same path passed as \`path\`.

Ops:
\`PUT N.=M:\` replaces original inclusive lines N-M with the body. \`PUT N*:\` replaces the syntactic block starting at line N (closing line auto-resolved). \`PUT <N:\` inserts before line N (\`PUT <1:\` = file head); \`PUT >N:\` inserts after line N (\`PUT >$:\` = file tail); \`PUT >N*:\` inserts after block N's end. \`CUT N.=M\` / \`CUT N*\` deletes and captures those lines/block, anonymously or into a named register (\`CUT N.=M @name\`); \`PUT <N @name\` / \`PUT >N @name\` pastes a register at that gap. \`REM\` deletes the file. \`MV dest\` moves/renames it (prior edits in the same section apply to the source; final content lands at dest).

Body rows only follow a \`:\` header: each is a verbatim \`+TEXT\` line (leading whitespace preserved, \`+\` alone is a blank line). There is no \`-old\`/bare/context row — the named range is deleted outright and the body is the complete replacement, so body length has nothing to do with range size. A single line is \`PUT N.=N:\` / \`CUT N.=N\`.

Rules: line numbers and TAGs always come from the latest read/search output and are never renumbered mid-edit — take fresh numbers from the next read or edit response before editing again. Only touch lines that were actually displayed; an elided/unseen line (\`...\`, collapsed \`N-M:\` rows) must be read first. Ranges cover only what changed — never widen a range to include lines you're keeping; separate non-adjacent changes into separate hunks. Named registers persist across edit calls; anonymous ones don't.

Example — read output shows \`[greet.py#A1B2]\` then numbered lines; to rewrite the function body and move the file:
\`\`\`
[greet.py#A1B2]
PUT 1.=3:
+def greet(name):
+    print(f"Hi, {name}")
MV lib/greet.py
\`\`\``;

const editSchema = {
	type: "object",
	properties: {
		path: {
			type: "string",
			description: "File path to edit (relative or absolute)",
		},
		edits: {
			type: "array",
			description:
				"Exact text replacements. Each must match a unique, " +
				"non-overlapping region of the original file. " +
				"If two changes touch the same block, merge them into one edit.",
			items: {
				type: "object",
				properties: {
					oldText: {
						type: "string",
						description: "Exact text to find and replace",
					},
					newText: { type: "string", description: "Replacement text" },
					replaceAll: {
						type: "boolean",
						description:
							"Replace every occurrence of oldText instead of requiring uniqueness. " +
							"Use for renaming a symbol throughout the file.",
					},
				},
			},
		},
		input: {
			type: "string",
			description:
				`${HASHLINE_INPUT_DESCRIPTION}\n\n` +
				"(Alternative to edits[]; when both are provided, input takes precedence.)",
		},
	},
	required: ["path"],
} as const;
function prepareArguments(raw: unknown): Record<string, unknown> {
	if (!raw || typeof raw !== "object" || Array.isArray(raw)) return {};
	const args = raw as Record<string, unknown>;

	const path =
		(typeof args.path === "string" && args.path) ||
		(typeof args.file_path === "string" && args.file_path) ||
		"";

	const oldText =
		(typeof args.oldText === "string" && args.oldText) ||
		(typeof args.old_text === "string" && args.old_text) ||
		(typeof args.oldString === "string" && args.oldString) ||
		"";
	const newText =
		(typeof args.newText === "string" && args.newText) ||
		(typeof args.new_text === "string" && args.new_text) ||
		(typeof args.newString === "string" && args.newString) ||
		"";
	const topReplaceAll = args.replaceAll === true || args.replace_all === true;

	let rawEdits = args.edits;
	if (typeof rawEdits === "string") {
		try {
			const parsed = JSON.parse(rawEdits);
			if (Array.isArray(parsed)) rawEdits = parsed;
		} catch (_e: unknown) {
			// Leave as-is
		}
	}

	const edits: Edit[] = [];
	if (oldText) {
		edits.push({ oldText, newText, replaceAll: topReplaceAll });
	}
	if (Array.isArray(rawEdits)) {
		for (const item of rawEdits) {
			if (!item || typeof item !== "object") continue;
			const e = item as Record<string, unknown>;
			const eOld =
				(typeof e.oldText === "string" && e.oldText) ||
				(typeof e.old_text === "string" && e.old_text) ||
				"";
			const eNew =
				(typeof e.newText === "string" && e.newText) ||
				(typeof e.new_text === "string" && e.new_text) ||
				"";
			if (eOld) {
				edits.push({
					oldText: eOld,
					newText: eNew,
					replaceAll: e.replaceAll === true || e.replace_all === true,
				});
			}
		}
	}

	const input =
		typeof args.input === "string" && args.input ? args.input : undefined;
	return { path, edits, input };
}

