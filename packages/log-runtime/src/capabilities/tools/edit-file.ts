export const edit: Tool = {
	name: "edit",
	executionMode: "parallel",
	label: "Edit File",
	hookAliases: ["Edit"],
	description:
		"Edit a single file using exact text replacement, anchored by a content-hash read of the file. " +
		"Every edits[].oldText must match a unique, " +
		"non-overlapping region of the original file " +
		"(or set replaceAll: true on an edit to replace every occurrence). " +
		"The file must have been read with read first; a stale anchor (file changed since that read) is detected and rejected. " +
		"Supports BOM handling and line-ending preservation.",
	promptSnippet:
		"Edit files using exact text replacement with precise matching",
	promptGuidelines: [
		"Use edit for surgical edits; keep oldText unique in the file, or set replaceAll for renames",
	],
	parameters: editSchema,
	prepareArguments,
	execute: async (
		args: Record<string, unknown>,
		ctx,
	): Promise<string | ToolResult> => {
		const path = String(args.path ?? "");
		const edits = (args.edits as Edit[]) || [];
		const input = String(args.input ?? "");

		if (!path) {
			return "Error: edit requires a path.";
		}

		if (input && edits.length > 0)
			return "Error: Use either input or text edits, not both.";
		if (!input && edits.length === 0) {
			return "Error: Provide oldText/newText or edits[].";
		}
		const resolved = resolveReadPath(path, ctx.cwd || process.cwd());
		ensureInsideCwd(ctx.cwd, resolved, ctx.allowedPaths, ctx.allowAllPaths);

		try {
			await defaultEditOperations.access(resolved);
		} catch (error: unknown) {
			const errorMessage =
				error instanceof Error && "code" in error
					? `Error code: ${(error as { code: string }).code}`
					: String(error);
			return `Could not edit file: ${path}. ${errorMessage}.`;
		}

		if (!hasBeenRead(resolved)) {
			return (
				`${resolved} has not been read yet. ` +
				"Read it with read before editing."
			);
		}
		const store = createEditStore();
		const mutation = createMutationSession(store, ctx.cwd || process.cwd(), {
			allowedPaths: ctx.allowedPaths,
			allowAllPaths: ctx.allowAllPaths,
		});

		return withFileMutationQueue(resolved, async () => {
			if (isStaleSinceRead(resolved)) {
				return (
					`${resolved} has been modified since it was last read. ` +
					"Read it again before editing."
				);
			}
			if (input) {
				const result = await runNativeHashlineEdit(
					input,
					resolved,
					ctx.cwd || process.cwd(),
					mutation,
				);
				const receipt = combineMutationReceipts(result.receipts);
				if (result.error)
					return {
						content: `Error: ${result.error}`,
						isError: true,
						details: { mutation: receipt },
					};
				if (!result.applied) {
					const noopWarning = store.recordNoop(resolved);
					if (noopWarning)
						return { content: noopWarning, details: { mutation: receipt } };
					return {
						content:
							"No changes made: hashline edits matched the current content.",
						details: { mutation: receipt },
					};
				}
				store.recordSuccess(resolved);
				refreshAfterWrite(resolved);
				// Auto-recovery: check parse after edit
				const hashlineParseError = await checkFileParse(resolved);
				if (hashlineParseError) {
					return {
						content:
							`Applied ${result.linesChanged} line change(s) across ${result.filesAffected} file(s).\n` +
							`\n⚠ Parse error detected after edit: ${hashlineParseError}` +
							(result.diff ? `\n\nDiff:\n${result.diff}` : ""),
						isError: true,
						details: {
							mutation: receipt,
							diff: result.diff,
							linesChanged: result.linesChanged,
							filesAffected: result.filesAffected,
							parseError: true,
						},
					};
				}
				return {
					content:
						`Applied ${result.linesChanged} line change(s) across ${result.filesAffected} file(s).` +
						(result.diff ? `\n\nDiff:\n${result.diff}` : ""),
					details: {
						mutation: receipt,
						diff: result.diff,
						linesChanged: result.linesChanged,
						filesAffected: result.filesAffected,
					},
				};
			}
			const native = await runNativeReplaceEdit(
				resolved,
				edits,
				ctx.cwd || process.cwd(),
				mutation,
			);
			refreshAfterWrite(resolved);

			if (native.error)
				return {
					content: `Error: ${native.error}`,
					isError: true,
					details: { mutation: native.mutation },
				};
			if (!native.mutation.changed) {
				const noopWarning = store.recordNoop(resolved);
				if (noopWarning)
					return {
						content: noopWarning,
						details: { mutation: native.mutation },
					};
				return {
					content: "No changes made: the edit produced identical content.",
					details: { mutation: native.mutation },
				};
			}
			store.recordSuccess(resolved);

			// Auto-recovery: check parse after edit
			const parseError = await checkFileParse(resolved);
			if (parseError) {
				return {
					content:
						`Successfully replaced ${edits.length} block(s) in ${path}.` +
						`\n\n⚠ Parse error detected after edit: ${parseError}` +
						(native.diff ? `\n\nDiff:\n${native.diff}` : ""),
					isError: true,
					details: {
						mutation: native.mutation,
						diff: native.diff,
						parseError: true,
					},
				};
			}

			return {
				content:
					`Successfully replaced ${edits.length} block(s) in ${path}.\n` +
					(native.diff ? `\n\nDiff:\n${native.diff}` : ""),
				details: {
					mutation: native.mutation,
					diff: native.diff,
				},
			};
		});
	},
};
