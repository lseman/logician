// ── edit tool ────────────────────────────────────────────────────────────────────
// Edit file contents with exact text replacement. Supports both single old_text/new_text
// and multi-edit arrays, plus replaceAll for renames. Matching (exact, then fuzzy) runs
// through @logician/log-natives' pi_edit engine (oh-my-pi's "replace" mode) rather than a
// local reimplementation — the same engine that ports pi's own edit tool. BOM handling and
// line-ending preservation happen inside that engine.

