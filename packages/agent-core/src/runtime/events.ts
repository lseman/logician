/** Event names are derived from the canonical discriminated union so the two
 * cannot drift as new runtime events are added. */
export type RuntimeEventType = RuntimeEvent["type"];

export type TranscriptEvent = Extract<
	RuntimeEvent,
	{
		type:
			| "turn_start"
			| "turn_end"
			| "token"
			| "thinking_token"
			| "message_update"
			| "message_reasoning_update"
			| "notice"
			| "tool_call_start"
			| "tool_call_update"
			| "tool_call_id_update"
			| "tool_execution_start"
			| "tool_execution_update"
			| "tool_execution_end"
			| "subagent_chunk"
			| "subagent_lifecycle";
	}
>;

export function isTranscriptEvent(
	event: RuntimeEvent,
): event is TranscriptEvent {
	switch (event.type) {
		case "turn_start":
		case "turn_end":
		case "token":
		case "thinking_token":
		case "message_update":
		case "message_reasoning_update":
		case "notice":
		case "tool_call_start":
		case "tool_call_update":
		case "tool_call_id_update":
		case "tool_execution_start":
		case "tool_execution_update":
		case "tool_execution_end":
		case "subagent_chunk":
		case "subagent_lifecycle":
			return true;
		default:
			return false;
	}
}
